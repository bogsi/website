#!/usr/bin/env node
// One-off import of the old Google Sheet into D1.
//
//   1. In Google Sheets: File → Download → Comma-separated values (.csv)
//   2. node scripts/import-sheet.mjs orders.csv > import.sql
//   3. npx wrangler d1 execute roussev-orders --remote --file import.sql
//
// Expected header (the Sheet's own): ID, Дата, Имена, Email, Компания,
// AWS Услуга, Описание, Бюджет, Срок, Статут. Columns are matched by name,
// so their order does not matter. Rows whose ID already exists are skipped
// (INSERT OR IGNORE), so the import can be re-run safely.

import { readFileSync } from "node:fs";

const file = process.argv[2];
if (!file) {
  console.error("usage: node scripts/import-sheet.mjs <orders.csv>");
  process.exit(1);
}

// RFC 4180 CSV: quoted fields may contain commas, quotes ("") and newlines.
function parseCsv(text) {
  const rows = [];
  let row = [], field = "", quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (ch === '"') quoted = false;
      else field += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ",") { row.push(field); field = ""; }
    else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && text[i + 1] === "\n") i++;
      row.push(field); rows.push(row); row = []; field = "";
    } else field += ch;
  }
  if (field !== "" || row.length) { row.push(field); rows.push(row); }
  return rows.filter((r) => r.some((c) => c.trim() !== ""));
}

// Header names normalised: lower-case, Latin "K" typo in "Kомпания" tolerated.
const norm = (h) => h.trim().toLowerCase().replace(/^k/, "к");
const COLUMNS = {
  id: ["id"],
  date: ["дата", "date"],
  name: ["имена", "name"],
  email: ["email", "имейл"],
  company: ["компания", "company"],
  service: ["aws услуга", "service", "услуга"],
  description: ["описание", "description"],
  budget: ["бюджет", "budget"],
  deadline: ["срок", "deadline"],
  status: ["статут", "статус", "status"],
};

const STATUS_MAP = {
  new: "new", нова: "new", нов: "new",
  contacted: "contacted", "свързан": "contacted", "свързах се": "contacted",
  quoted: "quoted", "оферта": "quoted", "изпратена оферта": "quoted",
  won: "won", "спечелена": "won", "приета": "won",
  lost: "lost", "загубена": "lost", "отказана": "lost",
  "in progress": "in_progress", in_progress: "in_progress", "в процес": "in_progress", "в работа": "in_progress",
  done: "done", "завършена": "done", "готова": "done",
};

const sql = (v) => (v === null ? "NULL" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);

const [header, ...rows] = parseCsv(readFileSync(file, "utf8").replace(/^﻿/, ""));
const index = {};
for (const [key, names] of Object.entries(COLUMNS)) {
  index[key] = header.findIndex((h) => names.includes(norm(h)));
}
const missing = ["id", "date", "name", "email", "service", "description"].filter((k) => index[k] < 0);
if (missing.length) {
  console.error(`Missing columns: ${missing.join(", ")}. Found header: ${header.join(" | ")}`);
  process.exit(1);
}

const get = (r, k) => (index[k] >= 0 ? (r[index[k]] ?? "").trim() : "");
const out = ["-- Generated by scripts/import-sheet.mjs (D1 runs a --file as one batch; no BEGIN/COMMIT allowed)"];
let count = 0, unknown = 0;

for (const r of rows) {
  const id = get(r, "id");
  if (!/^ORD-[A-Z0-9]{4,}$/i.test(id)) {
    console.error(`skip row without a valid ID: ${r.join(" | ").slice(0, 80)}`);
    continue;
  }
  const date = get(r, "date");
  const createdAt = /^\d{4}-\d{2}-\d{2}/.test(date) ? Date.parse(`${date.slice(0, 10)}T00:00:00Z`) : Date.now();
  const rawStatus = get(r, "status");
  const status = STATUS_MAP[rawStatus.toLowerCase()] ?? "new";
  const notes = rawStatus && !STATUS_MAP[rawStatus.toLowerCase()] ? `Imported status: ${rawStatus}` : "";
  if (notes) unknown++;

  out.push(
    `INSERT OR IGNORE INTO orders (id, created_at, updated_at, full_name, email, company, aws_service, description, budget, deadline, status, notes, source) VALUES (${[
      id.toUpperCase(), createdAt, createdAt, get(r, "name"), get(r, "email").toLowerCase(), get(r, "company"),
      get(r, "service"), get(r, "description"), get(r, "budget"), get(r, "deadline"), status, notes, "import",
    ].map(sql).join(", ")});`,
    `INSERT INTO order_events (order_id, at, actor, type, to_status, body) SELECT ${sql(id.toUpperCase())}, ${createdAt}, 'import', 'created', ${sql(status)}, 'Imported from Google Sheets' WHERE changes() > 0;`,
  );
  count++;
}
process.stdout.write(out.join("\n") + "\n");
console.error(`${count} orders written${unknown ? `, ${unknown} with an unrecognised status kept as "new" (original in notes)` : ""}.`);
